-- Runtime battle-simulator model.
-- Reads are exposed as database functions; mutations are exposed as procedures.

BEGIN;

CREATE TABLE IF NOT EXISTS game_instance.game_session (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    game_version_id bigint REFERENCES game_engine.game_version (game_version_id),
    game_mode_id bigint REFERENCES game_engine.game_mode (game_mode_id),
    scenario_id bigint REFERENCES game_engine.scenario_definition (scenario_id),
    session_name text NOT NULL,
    session_code text NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'setup',
    current_round integer NOT NULL DEFAULT 0,
    current_phase_id bigint REFERENCES game_engine.phase_definition (phase_id),
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT game_session_status_ck CHECK (status IN ('setup', 'running', 'paused', 'completed', 'cancelled')),
    CONSTRAINT game_session_round_ck CHECK (current_round >= 0)
);
ALTER TABLE game_instance.game_session
    ADD COLUMN IF NOT EXISTS fleet_format_id bigint REFERENCES game_engine.fleet_format (fleet_format_id);

CREATE TABLE IF NOT EXISTS game_instance.session_player (
    session_player_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    seat_number integer NOT NULL,
    display_name text NOT NULL,
    player_kind text NOT NULL DEFAULT 'human',
    faction_id bigint REFERENCES game_engine.faction (faction_id),
    is_ready boolean NOT NULL DEFAULT false,
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT session_player_seat_ck CHECK (seat_number > 0),
    CONSTRAINT session_player_kind_ck CHECK (player_kind IN ('human', 'cpu')),
    CONSTRAINT session_player_seat_uq UNIQUE (session_id, seat_number)
);

CREATE TABLE IF NOT EXISTS game_instance.player_fleet (
    fleet_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_player_id bigint NOT NULL REFERENCES game_instance.session_player (session_player_id) ON DELETE CASCADE,
    fleet_format_id bigint REFERENCES game_engine.fleet_format (fleet_format_id),
    fleet_name text NOT NULL,
    points_total integer,
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS game_instance.fleet_unit (
    unit_instance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_id bigint NOT NULL REFERENCES game_instance.player_fleet (fleet_id) ON DELETE CASCADE,
    unit_variant_id bigint NOT NULL REFERENCES game_engine.unit_variant (unit_variant_id),
    unit_name text NOT NULL,
    position_x numeric,
    position_y numeric,
    facing numeric,
    unit_status text NOT NULL DEFAULT 'ready',
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fleet_unit_status_ck CHECK (unit_status IN ('ready', 'activated', 'destroyed', 'withdrawn'))
);

CREATE TABLE IF NOT EXISTS game_instance.session_board (
    session_board_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    board_definition_id bigint NOT NULL REFERENCES game_engine.board_definition (board_definition_id),
    board_role text NOT NULL DEFAULT 'primary',
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT session_board_role_ck CHECK (board_role <> '')
);

CREATE TABLE IF NOT EXISTS game_instance.object_instance (
    object_instance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    owner_player_id bigint REFERENCES game_instance.session_player (session_player_id),
    zone_code text NOT NULL DEFAULT 'supply',
    location_index integer,
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS game_instance.session_turn (
    turn_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    round_number integer NOT NULL,
    phase_id bigint REFERENCES game_engine.phase_definition (phase_id),
    active_player_id bigint REFERENCES game_instance.session_player (session_player_id),
    turn_sequence integer NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    ended_at timestamptz,
    state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT session_turn_round_ck CHECK (round_number >= 0),
    CONSTRAINT session_turn_sequence_uq UNIQUE (session_id, turn_sequence)
);

CREATE TABLE IF NOT EXISTS game_instance.session_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    event_sequence bigint NOT NULL,
    event_type text NOT NULL,
    actor_player_id bigint REFERENCES game_instance.session_player (session_player_id),
    payload_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_event_sequence_uq UNIQUE (session_id, event_sequence)
);

CREATE INDEX IF NOT EXISTS session_game_status_idx
    ON game_instance.game_session (game_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS session_player_session_idx
    ON game_instance.session_player (session_id, seat_number);
CREATE INDEX IF NOT EXISTS fleet_unit_fleet_idx
    ON game_instance.fleet_unit (fleet_id);
CREATE INDEX IF NOT EXISTS session_event_session_idx
    ON game_instance.session_event (session_id, event_sequence);

CREATE OR REPLACE FUNCTION game_instance.fn_session_list(
    p_game_id bigint DEFAULT NULL,
    p_status text DEFAULT NULL
) RETURNS TABLE (
    session_id bigint,
    game_id bigint,
    game_name text,
    session_name text,
    session_code text,
    status text,
    current_round integer,
    player_count bigint,
    created_at timestamptz,
    updated_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT s.session_id, s.game_id, g.game_name, s.session_name, s.session_code,
           s.status, s.current_round, count(sp.session_player_id),
           s.created_at, s.updated_at
    FROM game_instance.game_session s
    JOIN game_engine.game g ON g.game_id = s.game_id
    LEFT JOIN game_instance.session_player sp ON sp.session_id = s.session_id
    WHERE (p_game_id IS NULL OR s.game_id = p_game_id)
      AND (p_status IS NULL OR s.status = p_status)
    GROUP BY s.session_id, g.game_name
    ORDER BY s.updated_at DESC, s.session_id DESC
$$;

DROP FUNCTION IF EXISTS game_instance.fn_session_get(bigint);
CREATE OR REPLACE FUNCTION game_instance.fn_session_get(p_session_id bigint)
RETURNS TABLE (
    session_id bigint,
    game_id bigint,
    game_name text,
    game_version_id bigint,
    game_mode_id bigint,
    scenario_id bigint,
    fleet_format_id bigint,
    session_name text,
    session_code text,
    status text,
    current_round integer,
    current_phase_id bigint,
    state_json jsonb,
    created_at timestamptz,
    updated_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT s.session_id, s.game_id, g.game_name, s.game_version_id,
           s.game_mode_id, s.scenario_id, s.fleet_format_id, s.session_name, s.session_code,
           s.status, s.current_round, s.current_phase_id, s.state_json,
           s.created_at, s.updated_at
    FROM game_instance.game_session s
    JOIN game_engine.game g ON g.game_id = s.game_id
    WHERE s.session_id = p_session_id
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_session_players(p_session_id bigint)
RETURNS TABLE (
    session_player_id bigint,
    session_id bigint,
    seat_number integer,
    display_name text,
    player_kind text,
    faction_id bigint,
    faction_name text,
    is_ready boolean,
    state_json jsonb
) LANGUAGE sql STABLE AS $$
    SELECT sp.session_player_id, sp.session_id, sp.seat_number,
           sp.display_name, sp.player_kind, sp.faction_id, f.faction_name,
           sp.is_ready, sp.state_json
    FROM game_instance.session_player sp
    LEFT JOIN game_engine.faction f ON f.faction_id = sp.faction_id
    WHERE sp.session_id = p_session_id
    ORDER BY sp.seat_number
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_player_get(p_session_player_id bigint)
RETURNS TABLE (
    session_player_id bigint,
    session_id bigint,
    seat_number integer,
    display_name text,
    player_kind text,
    faction_id bigint,
    faction_name text,
    is_ready boolean,
    state_json jsonb
) LANGUAGE sql STABLE AS $$
    SELECT sp.session_player_id, sp.session_id, sp.seat_number,
           sp.display_name, sp.player_kind, sp.faction_id, f.faction_name,
           sp.is_ready, sp.state_json
    FROM game_instance.session_player sp
    LEFT JOIN game_engine.faction f ON f.faction_id = sp.faction_id
    WHERE sp.session_player_id = p_session_player_id
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_session_units(p_session_id bigint)
RETURNS TABLE (
    unit_instance_id bigint,
    session_id bigint,
    session_player_id bigint,
    fleet_id bigint,
    unit_variant_id bigint,
    unit_name text,
    position_x numeric,
    position_y numeric,
    facing numeric,
    unit_status text,
    state_json jsonb
) LANGUAGE sql STABLE AS $$
    SELECT fu.unit_instance_id, sp.session_id, sp.session_player_id,
           fu.fleet_id, fu.unit_variant_id, fu.unit_name, fu.position_x,
           fu.position_y, fu.facing, fu.unit_status, fu.state_json
    FROM game_instance.fleet_unit fu
    JOIN game_instance.player_fleet pf ON pf.fleet_id = fu.fleet_id
    JOIN game_instance.session_player sp ON sp.session_player_id = pf.session_player_id
    WHERE sp.session_id = p_session_id
    ORDER BY fu.unit_instance_id
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_session_events(
    p_session_id bigint,
    p_after_sequence bigint DEFAULT 0
) RETURNS TABLE (
    event_id bigint,
    event_sequence bigint,
    event_type text,
    actor_player_id bigint,
    payload_json jsonb,
    created_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT event_id, event_sequence, event_type, actor_player_id,
           payload_json, created_at
    FROM game_instance.session_event
    WHERE session_id = p_session_id AND event_sequence > p_after_sequence
    ORDER BY event_sequence
$$;

DROP PROCEDURE IF EXISTS game_instance.sp_session_create(bigint, text, bigint, bigint, bigint);
CREATE OR REPLACE PROCEDURE game_instance.sp_session_create(
    IN p_game_id bigint,
    IN p_session_name text,
    IN p_game_mode_id bigint,
    IN p_scenario_id bigint,
    IN p_fleet_format_id bigint,
    INOUT p_session_id bigint
) LANGUAGE plpgsql AS $$
DECLARE
    v_code text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM game_engine.game WHERE game_id = p_game_id) THEN
        RAISE EXCEPTION 'Game % does not exist', p_game_id USING ERRCODE = '23503';
    END IF;
    IF p_game_mode_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM game_engine.game_mode WHERE game_mode_id = p_game_mode_id AND game_id = p_game_id
    ) THEN
        RAISE EXCEPTION 'Game mode % does not belong to game %', p_game_mode_id, p_game_id USING ERRCODE = '23503';
    END IF;
    IF p_scenario_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM game_engine.scenario_definition WHERE scenario_id = p_scenario_id AND game_id = p_game_id
    ) THEN
        RAISE EXCEPTION 'Scenario % does not belong to game %', p_scenario_id, p_game_id USING ERRCODE = '23503';
    END IF;
    IF p_fleet_format_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM game_engine.fleet_format ff
        JOIN game_engine.game_mode gm ON gm.game_mode_id = ff.game_mode_id
        WHERE ff.fleet_format_id = p_fleet_format_id AND gm.game_id = p_game_id
    ) THEN
        RAISE EXCEPTION 'Fleet format % does not belong to game %', p_fleet_format_id, p_game_id USING ERRCODE = '23503';
    END IF;
    v_code := 'SIM-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || txid_current();
    INSERT INTO game_instance.game_session (game_id, game_mode_id, scenario_id, fleet_format_id, session_name, session_code)
    VALUES (p_game_id, p_game_mode_id, p_scenario_id, p_fleet_format_id, p_session_name, v_code)
    RETURNING session_id INTO p_session_id;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_session_update(
    IN p_session_id bigint,
    IN p_status text,
    IN p_current_round integer,
    IN p_current_phase_id bigint,
    IN p_state_json text
) LANGUAGE plpgsql AS $$
BEGIN
    UPDATE game_instance.game_session
    SET status = COALESCE(p_status, status),
        current_round = COALESCE(p_current_round, current_round),
        current_phase_id = COALESCE(p_current_phase_id, current_phase_id),
        state_json = COALESCE(p_state_json::jsonb, state_json),
        updated_at = now()
    WHERE session_id = p_session_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Session % does not exist', p_session_id USING ERRCODE = 'P0002'; END IF;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_session_delete(IN p_session_id bigint)
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM game_instance.game_session WHERE session_id = p_session_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Session % does not exist', p_session_id USING ERRCODE = 'P0002'; END IF;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_player_create(
    IN p_session_id bigint,
    IN p_seat_number integer,
    IN p_display_name text,
    IN p_player_kind text,
    IN p_faction_id bigint,
    INOUT p_session_player_id bigint
) LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM game_instance.game_session WHERE session_id = p_session_id) THEN
        RAISE EXCEPTION 'Session % does not exist', p_session_id USING ERRCODE = '23503';
    END IF;
    INSERT INTO game_instance.session_player (session_id, seat_number, display_name, player_kind, faction_id)
    VALUES (p_session_id, p_seat_number, p_display_name, COALESCE(p_player_kind, 'human'), p_faction_id)
    RETURNING session_player_id INTO p_session_player_id;
    UPDATE game_instance.game_session SET updated_at = now() WHERE session_id = p_session_id;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_player_update(
    IN p_session_player_id bigint,
    IN p_display_name text,
    IN p_player_kind text,
    IN p_faction_id bigint,
    IN p_is_ready boolean,
    IN p_state_json text
) LANGUAGE plpgsql AS $$
BEGIN
    UPDATE game_instance.session_player
    SET display_name = COALESCE(p_display_name, display_name),
        player_kind = COALESCE(p_player_kind, player_kind),
        faction_id = COALESCE(p_faction_id, faction_id),
        is_ready = COALESCE(p_is_ready, is_ready),
        state_json = COALESCE(p_state_json::jsonb, state_json)
    WHERE session_player_id = p_session_player_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Player % does not exist', p_session_player_id USING ERRCODE = 'P0002'; END IF;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_player_delete(IN p_session_player_id bigint)
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM game_instance.session_player WHERE session_player_id = p_session_player_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Player % does not exist', p_session_player_id USING ERRCODE = 'P0002'; END IF;
END
$$;

COMMIT;
