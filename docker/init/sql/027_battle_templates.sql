-- Persistent battle setup templates and links from runtime sessions.

BEGIN;

CREATE TABLE IF NOT EXISTS game_instance.battle_template (
    template_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    template_key text NOT NULL UNIQUE,
    template_name text NOT NULL,
    description text NOT NULL DEFAULT '',
    game_version_id bigint REFERENCES game_engine.game_version (game_version_id),
    game_mode_id bigint REFERENCES game_engine.game_mode (game_mode_id),
    scenario_id bigint REFERENCES game_engine.scenario_definition (scenario_id),
    fleet_format_id bigint REFERENCES game_engine.fleet_format (fleet_format_id),
    board_code text NOT NULL,
    board_width numeric NOT NULL,
    board_height numeric NOT NULL,
    options_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    players_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    template_session_id bigint UNIQUE REFERENCES game_instance.game_session (session_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE game_instance.game_session
    ADD COLUMN IF NOT EXISTS template_id bigint REFERENCES game_instance.battle_template (template_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS battle_template_game_idx
    ON game_instance.battle_template (game_id, template_name);
CREATE INDEX IF NOT EXISTS game_session_template_idx
    ON game_instance.game_session (template_id, updated_at DESC);

COMMIT;
