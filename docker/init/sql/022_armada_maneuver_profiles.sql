        ('Galactic Republic', 'Venator-class Star Destroyer', '[[1],[1,1],[0,1,0]]'::jsonb),
        ('Galactic Republic', 'Pelta-class Frigate', '[[2],[1,1]]'::jsonb),
        ('Galactic Republic', 'Victory-class Star Destroyer', '[[1],[0,1]]'::jsonb),
        ('Separatist Alliance', 'Hardcell-class', '[[2],[1,1],[1,1,0]]'::jsonb),
        ('Separatist Alliance', 'Munificent-class Frigate', '[[1],[1,2]]'::jsonb),
        ('Separatist Alliance', 'Recusant-class Destroyer', '[[1],[1,1],[0,2,1]]'::jsonb),
        ('Separatist Alliance', 'Providence-class Dreadnaught Carrier', '[[2],[1,1],[1,0,0]]'::jsonb),
        ('Separatist Alliance', 'Gozanti-class Flotilla', '[[2],[1,1],[1,1,0]]'::jsonb)
), matched AS (
    SELECT uv.unit_variant_id, c.chart
    FROM charts c
    JOIN game_engine.unit_type ut ON ut.unit_type_name = c.unit_type_name
    JOIN game_engine.unit_classification uc ON uc.unit_classification_id = ut.unit_classification_id
    JOIN game_engine.faction f ON f.faction_id = uc.faction_id
        AND f.faction_name = c.faction_name
    JOIN game_engine.unit_variant uv ON uv.unit_type_id = ut.unit_type_id
    WHERE uc.unit_classification_name = 'Ship'
)
