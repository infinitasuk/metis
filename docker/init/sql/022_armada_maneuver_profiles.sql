-- Import the per-speed maneuver charts used by the Armada Tabletop Simulator definitions.
-- I = 1 yaw click, II = 2 yaw clicks, and - = 0 yaw clicks.

BEGIN;

CREATE TABLE IF NOT EXISTS game_engine.unit_variant_maneuver_profile (
    unit_variant_maneuver_profile_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_variant_id bigint NOT NULL REFERENCES game_engine.unit_variant (unit_variant_id),
    speed integer NOT NULL CHECK (speed >= 0),
    maximum_yaw_clicks jsonb NOT NULL,
    source_reference_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT unit_variant_maneuver_profile_shape_ck
        CHECK (jsonb_typeof(maximum_yaw_clicks) = 'array'),
    CONSTRAINT unit_variant_maneuver_profile_owner_uq
        UNIQUE (unit_variant_id, speed)
);

WITH charts (faction_name, unit_type_name, chart) AS (
    VALUES
        ('Rebel Alliance', 'GR-75 Transport Flotilla', '[[2],[1,2],[0,1,2]]'::jsonb),
        ('Rebel Alliance', 'CR90 Corvette', '[[2],[1,2],[0,1,2],[0,1,1,2]]'::jsonb),
        ('Rebel Alliance', 'Nebulon-B Frigate', '[[1],[1,1],[0,1,2]]'::jsonb),
        ('Rebel Alliance', 'MC30c Frigate', '[[1],[1,1],[0,1,2],[0,1,1,0]]'::jsonb),
        ('Rebel Alliance', 'Modified Pelta-class Ship', '[[2],[1,1]]'::jsonb),
        ('Rebel Alliance', 'Hammerhead Corvette', '[[2],[2,1],[1,1,0]]'::jsonb),
        ('Rebel Alliance', 'Assault Frigate Mk II', '[[1],[1,1],[0,1,1]]'::jsonb),
        ('Rebel Alliance', 'MC80 Cruiser (Home One type)', '[[1],[1,1]]'::jsonb),
        ('Rebel Alliance', 'MC80 Cruiser (Liberty type)', '[[1],[1,0],[1,0,1]]'::jsonb),
        ('Rebel Alliance', 'MC75 Cruiser', '[[2],[1,1],[0,1,1]]'::jsonb),
        ('Rebel Alliance', 'Starhawk-Class Battleship', '[[1],[1,1]]'::jsonb),
        ('Rebel Alliance', 'Providence-class Dreadnaught Carrier', '[[1],[1,0]]'::jsonb),
        ('Galactic Empire', 'Gozanti-class Flotilla', '[[2],[1,1],[1,1,0]]'::jsonb),
        ('Galactic Empire', 'Raider-class Corvette', '[[2],[2,2],[0,1,1],[0,1,1,1]]'::jsonb),
        ('Galactic Empire', 'Gladiator-class Star Destroyer', '[[2],[1,1],[0,1,1]]'::jsonb),
        ('Galactic Empire', 'Arquitens-class Cruiser', '[[2],[0,2],[0,0,2]]'::jsonb),
        ('Galactic Empire', 'Victory-class Star Destroyer', '[[1],[0,1]]'::jsonb),
        ('Galactic Empire', 'Interdictor', '[[1],[1,1]]'::jsonb),
        ('Galactic Empire', 'Quasar Fire Cruiser-Carrier', '[[2],[1,1],[0,1,1]]'::jsonb),
        ('Galactic Empire', 'Imperial-class Star Destroyer', '[[1],[1,1],[0,1,1]]'::jsonb),
        ('Galactic Empire', 'Star Dreadnought', '[[0],[0,0]]'::jsonb),
        ('Galactic Empire', 'Onager-class Star Destroyer', '[[1],[1,1],[1,1,0]]'::jsonb),
        ('Galactic Empire', 'Venator-class Star Destroyer', '[[1],[1,1],[0,1,0]]'::jsonb),
