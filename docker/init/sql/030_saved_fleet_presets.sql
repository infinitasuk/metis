-- Player-owned fleet lists that can be reused when starting a battle.

BEGIN;

CREATE TABLE IF NOT EXISTS game_instance.fleet_preset (
    fleet_preset_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL REFERENCES game_instance.app_user (user_id) ON DELETE CASCADE,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    game_version_id bigint NOT NULL REFERENCES game_engine.game_version (game_version_id),
    fleet_format_id bigint REFERENCES game_engine.fleet_format (fleet_format_id),
    faction_id bigint NOT NULL REFERENCES game_engine.faction (faction_id),
    preset_name text NOT NULL,
    points_total integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fleet_preset_name_ck CHECK (length(trim(preset_name)) > 0),
    CONSTRAINT fleet_preset_points_ck CHECK (points_total IS NULL OR points_total >= 0)
);

CREATE TABLE IF NOT EXISTS game_instance.fleet_preset_unit (
    fleet_preset_unit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_preset_id bigint NOT NULL REFERENCES game_instance.fleet_preset (fleet_preset_id) ON DELETE CASCADE,
    unit_variant_id bigint NOT NULL REFERENCES game_engine.unit_variant (unit_variant_id),
    unit_name text NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    layout_x numeric NOT NULL DEFAULT 50,
    layout_y numeric NOT NULL DEFAULT 50,
    CONSTRAINT fleet_preset_unit_quantity_ck CHECK (quantity > 0),
    CONSTRAINT fleet_preset_unit_layout_x_ck CHECK (layout_x >= 0 AND layout_x <= 100),
    CONSTRAINT fleet_preset_unit_layout_y_ck CHECK (layout_y >= 0 AND layout_y <= 100)
);

ALTER TABLE game_instance.fleet_preset_unit
    ADD COLUMN IF NOT EXISTS layout_x numeric NOT NULL DEFAULT 50,
    ADD COLUMN IF NOT EXISTS layout_y numeric NOT NULL DEFAULT 50;
ALTER TABLE game_instance.fleet_preset_unit
    DROP CONSTRAINT IF EXISTS fleet_preset_unit_uq;
ALTER TABLE game_instance.fleet_preset_unit
    DROP CONSTRAINT IF EXISTS fleet_preset_unit_layout_x_ck,
    DROP CONSTRAINT IF EXISTS fleet_preset_unit_layout_y_ck;
ALTER TABLE game_instance.fleet_preset_unit
    ADD CONSTRAINT fleet_preset_unit_layout_x_ck CHECK (layout_x >= 0 AND layout_x <= 100),
    ADD CONSTRAINT fleet_preset_unit_layout_y_ck CHECK (layout_y >= 0 AND layout_y <= 100);

CREATE INDEX IF NOT EXISTS fleet_preset_owner_game_idx
    ON game_instance.fleet_preset (owner_user_id, game_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS fleet_preset_unit_preset_idx
    ON game_instance.fleet_preset_unit (fleet_preset_id);

COMMIT;
