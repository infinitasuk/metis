UPDATE game_engine.game_version gv
SET definition_game_name = g.game_name,
    definition_game_description = g.game_description,
    definition_min_players = g.minimum_number_of_players,
    definition_max_players = g.maximum_number_of_players,
    definition_min_cpu = g.minimum_number_of_cpu,
    definition_max_cpu = g.maximum_number_of_cpu
FROM game_engine.game g
WHERE g.game_id = gv.game_id
  AND gv.definition_game_name IS NULL;

CREATE OR REPLACE FUNCTION game_engine.trg_definition_version_defaults()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_source game_engine.game_version%ROWTYPE;
    v_game game_engine.game%ROWTYPE;
BEGIN
    IF NEW.definition_game_name IS NOT NULL THEN
        RETURN NEW;
    END IF;
    SELECT * INTO v_source
    FROM game_engine.game_version
    WHERE game_id = NEW.game_id AND lifecycle_status = 'published'
    ORDER BY published_at DESC NULLS LAST, game_version_id DESC
    LIMIT 1;
    SELECT * INTO v_game FROM game_engine.game WHERE game_id = NEW.game_id;
    NEW.definition_game_name := COALESCE(v_source.definition_game_name, v_game.game_name);
    NEW.definition_game_description := COALESCE(v_source.definition_game_description, v_game.game_description);
    NEW.definition_min_players := COALESCE(v_source.definition_min_players, v_game.minimum_number_of_players);
    NEW.definition_max_players := COALESCE(v_source.definition_max_players, v_game.maximum_number_of_players);
    NEW.definition_min_cpu := COALESCE(v_source.definition_min_cpu, v_game.minimum_number_of_cpu);
    NEW.definition_max_cpu := COALESCE(v_source.definition_max_cpu, v_game.maximum_number_of_cpu);
    RETURN NEW;
END
$$;

