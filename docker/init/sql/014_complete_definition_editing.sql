CREATE TABLE IF NOT EXISTS game_engine.definition_audit (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_version_id bigint NOT NULL REFERENCES game_engine.game_version (game_version_id),
    action_code text NOT NULL,
    entity_type text NOT NULL,
    entity_id bigint,
    details_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION game_engine.fn_definition_audit(p_definition_id bigint)
RETURNS TABLE (
    audit_id bigint,
    action_code text,
    entity_type text,
    entity_id bigint,
    details_json jsonb,
    occurred_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT audit_id, action_code, entity_type, entity_id, details_json, occurred_at
    FROM game_engine.definition_audit
    WHERE game_version_id = p_definition_id
    ORDER BY occurred_at DESC, audit_id DESC
$$;

CREATE OR REPLACE FUNCTION game_engine.fn_definition_version_validate(p_definition_id bigint)
RETURNS TABLE (is_valid boolean, errors jsonb)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_game_id bigint;
    v_errors jsonb := '[]'::jsonb;
BEGIN
    SELECT game_id INTO v_game_id
    FROM game_engine.game_version
    WHERE game_version_id = p_definition_id;

    IF NOT FOUND THEN
        RETURN QUERY SELECT false, jsonb_build_array(jsonb_build_object(
            'code', 'DEFINITION_NOT_FOUND', 'message', 'Definition revision does not exist'));
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM game_engine.game_version
                   WHERE game_version_id = p_definition_id
                     AND nullif(trim(version_code), '') IS NOT NULL) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'VERSION_CODE_REQUIRED', 'message', 'A version code is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.game_version
                   WHERE game_version_id = p_definition_id
                     AND nullif(trim(version_name), '') IS NOT NULL) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'VERSION_NAME_REQUIRED', 'message', 'A version name is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.faction WHERE game_version_id = p_definition_id) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'FACTIONS_REQUIRED', 'message', 'At least one faction is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.game_mode WHERE game_version_id = p_definition_id) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'GAME_MODE_REQUIRED', 'message', 'At least one game mode is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.phase_definition WHERE game_version_id = p_definition_id) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'PHASES_REQUIRED', 'message', 'At least one phase is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.scenario_definition WHERE game_version_id = p_definition_id) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'SCENARIOS_REQUIRED', 'message', 'At least one scenario is required'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_engine.board_definition WHERE game_version_id = p_definition_id) THEN
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
            'code', 'BOARDS_REQUIRED', 'message', 'At least one board is required'));
    END IF;

    RETURN QUERY SELECT jsonb_array_length(v_errors) = 0, v_errors;
END
$$;

CREATE OR REPLACE FUNCTION game_engine.fn_definition_audit_record(
    p_definition_id bigint,
    p_action_code text,
    p_entity_type text,
    p_entity_id bigint,
    p_details jsonb DEFAULT '{}'::jsonb
) RETURNS void LANGUAGE sql AS $$
    INSERT INTO game_engine.definition_audit
        (game_version_id, action_code, entity_type, entity_id, details_json)
    VALUES (p_definition_id, p_action_code, p_entity_type, p_entity_id, COALESCE(p_details, '{}'::jsonb))
$$;

CREATE OR REPLACE PROCEDURE game_engine.sp_definition_game_update(
    IN p_definition_id bigint,
    IN p_game_name text,
    IN p_game_description text,
    IN p_min_players integer,
    IN p_max_players integer,
    IN p_min_cpu integer,
    IN p_max_cpu integer
) LANGUAGE plpgsql AS $$
BEGIN
    UPDATE game_engine.game_version
    SET definition_game_name = p_game_name,
        definition_game_description = p_game_description,
        definition_min_players = p_min_players,
        definition_max_players = p_max_players,
        definition_min_cpu = p_min_cpu,
        definition_max_cpu = p_max_cpu,
        updated_at = now()
    WHERE game_version_id = p_definition_id AND lifecycle_status = 'draft';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Only draft definitions can be edited' USING ERRCODE = '55000';
    END IF;
    PERFORM game_engine.fn_definition_audit_record(p_definition_id, 'update', 'game', null,
        jsonb_build_object('name', p_game_name));
END
$$;

