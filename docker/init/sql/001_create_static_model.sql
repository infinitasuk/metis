-- METIS static game-definition model.
-- Static definitions live in game_engine; runtime match data lives in game_instance.

CREATE SCHEMA game_engine;
CREATE SCHEMA game_instance;

COMMENT ON SCHEMA game_engine IS
    'Versioned game definitions, catalogue content, rules and scenario configuration.';
COMMENT ON SCHEMA game_instance IS
    'User match instances, runtime state, actions and results.';

CREATE TABLE game_engine.game (
    game_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_name text NOT NULL,
    game_description text,
    minimum_number_of_players integer NOT NULL,
    maximum_number_of_players integer NOT NULL,
    minimum_number_of_cpu integer NOT NULL,
    maximum_number_of_cpu integer NOT NULL,
    CONSTRAINT game_player_range_ck
        CHECK (minimum_number_of_players >= 1
            AND maximum_number_of_players >= minimum_number_of_players),
    CONSTRAINT game_cpu_range_ck
        CHECK (minimum_number_of_cpu >= 0
            AND maximum_number_of_cpu >= minimum_number_of_cpu)
);

CREATE TABLE game_engine.content_source (
    content_source_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code text NOT NULL UNIQUE,
    source_name text NOT NULL,
    source_url text,
    licence text
);

CREATE TABLE game_engine.game_version (
    game_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    content_source_id bigint REFERENCES game_engine.content_source (content_source_id),
    version_code text NOT NULL,
    version_name text NOT NULL,
    release_date date,
    source_revision text,
    version_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT game_version_game_code_uq UNIQUE (game_id, version_code)
);

CREATE TABLE game_engine.faction (
    faction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    faction_name text NOT NULL,
    faction_description text
);

CREATE TABLE game_engine.unit_classification (
    unit_classification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faction_id bigint NOT NULL REFERENCES game_engine.faction (faction_id),
    unit_classification_name text NOT NULL,
    unit_classification_description text
);

CREATE TABLE game_engine.unit_type (
    unit_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_classification_id bigint NOT NULL
        REFERENCES game_engine.unit_classification (unit_classification_id),
    unit_type_name text NOT NULL,
    unit_type_description text
);

CREATE TABLE game_engine.unit_variant (
    unit_variant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_type_id bigint NOT NULL REFERENCES game_engine.unit_type (unit_type_id),
    unit_variant_name text NOT NULL,
    unit_variant_description text
);

CREATE TABLE game_engine.terrain_type (
    terrain_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    terrain_type_name text NOT NULL,
    terrain_type text,
    default_characteristic_json jsonb
);

CREATE TABLE game_engine.game_rule (
    game_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    game_rule_name text NOT NULL,
    game_rule_description text,
    game_rule_characteristic_json jsonb
);

CREATE TABLE game_engine.game_mode (
    game_mode_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    parent_game_mode_id bigint REFERENCES game_engine.game_mode (game_mode_id),
    game_mode_code text NOT NULL,
    game_mode_name text NOT NULL,
    game_mode_description text,
    mode_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_game_code_uq
        UNIQUE (game_id, game_mode_code)
);

CREATE TABLE game_engine.game_mode_rule (
    game_mode_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    game_rule_id bigint NOT NULL REFERENCES game_engine.game_rule (game_rule_id),
    rule_order integer NOT NULL DEFAULT 0,
    rule_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_rule_order_ck
        CHECK (rule_order >= 0),
    CONSTRAINT game_mode_rule_owner_uq
        UNIQUE (game_mode_id, game_rule_id),
    CONSTRAINT game_mode_rule_order_uq
        UNIQUE (game_mode_id, rule_order)
);

CREATE TABLE game_engine.phase_definition (
    phase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    phase_code text NOT NULL,
    phase_name text NOT NULL,
    phase_description text,
    phase_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT phase_game_code_uq UNIQUE (game_id, phase_code)
);

CREATE TABLE game_engine.game_mode_phase (
    game_mode_phase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    phase_id bigint NOT NULL REFERENCES game_engine.phase_definition (phase_id),
    phase_order integer NOT NULL,
    phase_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_phase_order_ck CHECK (phase_order >= 0),
    CONSTRAINT game_mode_phase_owner_uq UNIQUE (game_mode_id, phase_id),
    CONSTRAINT game_mode_phase_order_uq UNIQUE (game_mode_id, phase_order)
);

CREATE TABLE game_engine.action_definition (
    action_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    action_code text NOT NULL,
    action_name text NOT NULL,
    action_description text,
    action_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT action_game_code_uq UNIQUE (game_id, action_code)
);

CREATE TABLE game_engine.scenario_definition (
    scenario_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    scenario_code text NOT NULL,
    scenario_name text NOT NULL,
    scenario_description text,
    scenario_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT scenario_game_code_uq UNIQUE (game_id, scenario_code)
);

CREATE TABLE game_engine.game_mode_scenario (
    game_mode_scenario_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    scenario_id bigint NOT NULL REFERENCES game_engine.scenario_definition (scenario_id),
    is_default boolean NOT NULL DEFAULT false,
    scenario_order integer NOT NULL DEFAULT 0,
    scenario_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_scenario_owner_uq UNIQUE (game_mode_id, scenario_id)
);

CREATE TABLE game_engine.board_definition (
    board_definition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    board_code text NOT NULL,
    board_name text NOT NULL,
    width numeric,
    height numeric,
    coordinate_system text,
    board_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT board_game_code_uq UNIQUE (game_id, board_code)
);

CREATE TABLE game_engine.scenario_board (
    scenario_board_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id bigint NOT NULL REFERENCES game_engine.scenario_definition (scenario_id),
    board_definition_id bigint NOT NULL REFERENCES game_engine.board_definition (board_definition_id),
    board_role text NOT NULL DEFAULT 'primary',
    board_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT scenario_board_owner_uq UNIQUE (scenario_id, board_definition_id)
);

CREATE TABLE game_engine.fleet_format (
    fleet_format_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    format_code text NOT NULL,
    format_name text NOT NULL,
    points_limit integer,
    format_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fleet_format_mode_code_uq UNIQUE (game_mode_id, format_code)
);

CREATE TABLE game_engine.fleet_format_faction (
    fleet_format_id bigint NOT NULL REFERENCES game_engine.fleet_format (fleet_format_id),
    faction_id bigint NOT NULL REFERENCES game_engine.faction (faction_id),
    PRIMARY KEY (fleet_format_id, faction_id)
);

CREATE TABLE game_engine.fleet_unit_limit (
    fleet_unit_limit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_format_id bigint NOT NULL REFERENCES game_engine.fleet_format (fleet_format_id),
    unit_classification_id bigint REFERENCES game_engine.unit_classification (unit_classification_id),
    unit_type_id bigint REFERENCES game_engine.unit_type (unit_type_id),
    minimum_count integer NOT NULL DEFAULT 0,
    maximum_count integer,
    limit_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fleet_unit_limit_min_ck CHECK (minimum_count >= 0),
    CONSTRAINT fleet_unit_limit_max_ck CHECK (maximum_count IS NULL OR maximum_count >= minimum_count)
);

CREATE TABLE game_engine.characteristic_type (
    characteristic_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    characteristic_type_name text NOT NULL,
    characteristic_type_description text,
    CONSTRAINT characteristic_type_name_uq UNIQUE (characteristic_type_name)
);

CREATE TABLE game_engine.unit_type_characteristic (
    unit_type_characteristic_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_type_id bigint NOT NULL REFERENCES game_engine.unit_type (unit_type_id),
    characteristic_type_id bigint NOT NULL
        REFERENCES game_engine.characteristic_type (characteristic_type_id),
    characteristic_json jsonb NOT NULL,
    CONSTRAINT unit_type_characteristic_owner_uq
        UNIQUE (unit_type_id, characteristic_type_id)
);

CREATE TABLE game_engine.unit_variant_characteristic (
    unit_variant_characteristic_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_variant_id bigint NOT NULL REFERENCES game_engine.unit_variant (unit_variant_id),
    characteristic_type_id bigint NOT NULL
        REFERENCES game_engine.characteristic_type (characteristic_type_id),
    characteristic_json jsonb NOT NULL,
    CONSTRAINT unit_variant_characteristic_owner_uq
        UNIQUE (unit_variant_id, characteristic_type_id)
);

CREATE TABLE game_engine.game_object_type (
    game_object_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    object_type_code text NOT NULL,
    object_type_name text NOT NULL,
    object_kind text NOT NULL,
    validation_schema_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_object_type_game_code_uq UNIQUE (game_id, object_type_code)
);

CREATE TABLE game_engine.game_object (
    game_object_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    game_object_type_id bigint NOT NULL REFERENCES game_engine.game_object_type (game_object_type_id),
    object_code text NOT NULL,
    object_name text NOT NULL,
    object_description text,
    display_text text,
    object_data_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    source_reference_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_object_game_code_uq UNIQUE (game_id, object_code)
);

CREATE TABLE game_engine.game_object_relation (
    game_object_relation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    target_game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    relation_type text NOT NULL,
    relation_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_object_relation_owner_uq
        UNIQUE (source_game_object_id, target_game_object_id, relation_type),
    CONSTRAINT game_object_relation_self_ck
        CHECK (source_game_object_id <> target_game_object_id)
);

CREATE TABLE game_engine.game_object_eligibility (
    game_object_eligibility_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    faction_id bigint REFERENCES game_engine.faction (faction_id),
    unit_classification_id bigint REFERENCES game_engine.unit_classification (unit_classification_id),
    unit_type_id bigint REFERENCES game_engine.unit_type (unit_type_id),
    unit_variant_id bigint REFERENCES game_engine.unit_variant (unit_variant_id),
    game_mode_id bigint REFERENCES game_engine.game_mode (game_mode_id),
    eligibility_type text NOT NULL,
    condition_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_object_eligibility_type_ck
        CHECK (eligibility_type IN ('include', 'exclude')),
    CONSTRAINT game_object_eligibility_one_target_ck
        CHECK (num_nonnulls(faction_id, unit_classification_id, unit_type_id, unit_variant_id, game_mode_id) = 1)
);

CREATE TABLE game_engine.unit_variant_game_object (
    unit_variant_id bigint NOT NULL REFERENCES game_engine.unit_variant (unit_variant_id),
    game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    usage_code text NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    usage_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (unit_variant_id, game_object_id, usage_code),
    CONSTRAINT unit_variant_game_object_quantity_ck CHECK (quantity > 0)
);

CREATE TABLE game_engine.game_mode_game_object (
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    usage_code text NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    usage_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (game_mode_id, game_object_id, usage_code),
    CONSTRAINT game_mode_game_object_quantity_ck CHECK (quantity > 0)
);

CREATE TABLE game_engine.scenario_game_object (
    scenario_id bigint NOT NULL REFERENCES game_engine.scenario_definition (scenario_id),
    game_object_id bigint NOT NULL REFERENCES game_engine.game_object (game_object_id),
    usage_code text NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    usage_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (scenario_id, game_object_id, usage_code),
    CONSTRAINT scenario_game_object_quantity_ck CHECK (quantity > 0)
);
