    (2, 'bob', 'Bob', 'user'),
    (3, 'carol', 'Carol', 'user'),
    (4, 'dave', 'Dave', 'user'),
    (5, 'admin', 'METIS Administrator', 'admin')
ON CONFLICT (user_id) DO UPDATE
SET username = EXCLUDED.username,
    display_name = EXCLUDED.display_name,
    role_code = EXCLUDED.role_code,
    active = EXCLUDED.active;

SELECT setval(pg_get_serial_sequence('game_instance.app_user', 'user_id'),
              GREATEST((SELECT MAX(user_id) FROM game_instance.app_user), 1), true);

ALTER TABLE game_instance.game_session
    ADD COLUMN IF NOT EXISTS owner_user_id bigint REFERENCES game_instance.app_user (user_id);

CREATE TABLE IF NOT EXISTS game_instance.session_invitation (
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES game_instance.app_user (user_id) ON DELETE CASCADE,
    invited_by_user_id bigint NOT NULL REFERENCES game_instance.app_user (user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (session_id, user_id)
);

CREATE INDEX IF NOT EXISTS game_session_owner_idx
    ON game_instance.game_session (owner_user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS session_invitation_user_idx
    ON game_instance.session_invitation (user_id, session_id);

DROP FUNCTION IF EXISTS game_instance.fn_session_list(bigint, text);
CREATE OR REPLACE FUNCTION game_instance.fn_session_list(
    p_game_id bigint DEFAULT NULL,
    p_status text DEFAULT NULL
) RETURNS TABLE (
    session_id bigint,
    game_id bigint,
    game_name text,
    session_name text,
    session_code text,
    visibility text,
    owner_user_id bigint,
    status text,
    current_round integer,
    player_count bigint,
    created_at timestamptz,
    updated_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT s.session_id, s.game_id, g.game_name, s.session_name, s.session_code,
           s.visibility, s.owner_user_id, s.status, s.current_round,
           count(sp.session_player_id), s.created_at, s.updated_at
    FROM game_instance.game_session s
    JOIN game_engine.game g ON g.game_id = s.game_id
    LEFT JOIN game_instance.session_player sp ON sp.session_id = s.session_id
    WHERE (p_game_id IS NULL OR s.game_id = p_game_id)
      AND (p_status IS NULL OR s.status = p_status)
    GROUP BY s.session_id, g.game_name
    ORDER BY s.updated_at DESC, s.session_id DESC
$$;

DROP FUNCTION IF EXISTS game_instance.fn_session_get(bigint);
CREATE OR REPLACE FUNCTION game_instance.fn_session_get(p_session_id bigint)
RETURNS TABLE (
    session_id bigint,
    game_id bigint,
    game_name text,
    game_version_id bigint,
    game_version_code text,
    game_mode_id bigint,
    scenario_id bigint,
    fleet_format_id bigint,
    session_name text,
    session_code text,
    visibility text,
    owner_user_id bigint,
    status text,
    current_round integer,
    current_phase_id bigint,
    state_json jsonb,
    state_version bigint,
    engine_version text,
    api_version text,
    event_schema_version integer,
    created_at timestamptz,
    updated_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT s.session_id, s.game_id, g.game_name, s.game_version_id,
           gv.version_code, s.game_mode_id, s.scenario_id, s.fleet_format_id,
           s.session_name, s.session_code, s.visibility, s.owner_user_id,
           s.status, s.current_round, s.current_phase_id, s.state_json,
           s.state_version, s.engine_version, s.api_version,
           s.event_schema_version, s.created_at, s.updated_at
    FROM game_instance.game_session s
    JOIN game_engine.game g ON g.game_id = s.game_id
    LEFT JOIN game_engine.game_version gv ON gv.game_version_id = s.game_version_id
    WHERE s.session_id = p_session_id
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_session_can_view(
    p_session_id bigint, p_user_id bigint, p_is_admin boolean
) RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
        FROM game_instance.game_session s
        WHERE s.session_id = p_session_id
          AND (p_is_admin
               OR s.visibility = 'public'
               OR s.owner_user_id = p_user_id
               OR EXISTS (
                   SELECT 1 FROM game_instance.session_invitation i
                   WHERE i.session_id = s.session_id AND i.user_id = p_user_id
               ))
    )
$$;

CREATE OR REPLACE FUNCTION game_instance.fn_session_can_edit(
    p_session_id bigint, p_user_id bigint, p_is_admin boolean
) RETURNS boolean LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1 FROM game_instance.game_session s
        WHERE s.session_id = p_session_id
          AND (p_is_admin OR s.owner_user_id = p_user_id)
    )
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_session_owner_set(
    IN p_session_id bigint, IN p_owner_user_id bigint
) LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM game_instance.app_user WHERE user_id = p_owner_user_id AND active) THEN
        RAISE EXCEPTION 'User % does not exist or is inactive', p_owner_user_id USING ERRCODE = '23503';
    END IF;
    UPDATE game_instance.game_session
    SET owner_user_id = p_owner_user_id, updated_at = now()
    WHERE session_id = p_session_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Session % does not exist', p_session_id USING ERRCODE = 'P0002';
    END IF;
END
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_session_invite(
    IN p_session_id bigint, IN p_user_id bigint, IN p_invited_by_user_id bigint
) LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM game_instance.game_session WHERE session_id = p_session_id) THEN
        RAISE EXCEPTION 'Session % does not exist', p_session_id USING ERRCODE = 'P0002';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_instance.app_user WHERE user_id = p_user_id AND active) THEN
        RAISE EXCEPTION 'User % does not exist or is inactive', p_user_id USING ERRCODE = '23503';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM game_instance.app_user WHERE user_id = p_invited_by_user_id AND active) THEN
        RAISE EXCEPTION 'Inviting user % does not exist or is inactive', p_invited_by_user_id USING ERRCODE = '23503';
    END IF;
    INSERT INTO game_instance.session_invitation (session_id, user_id, invited_by_user_id)
    VALUES (p_session_id, p_user_id, p_invited_by_user_id)
    ON CONFLICT (session_id, user_id) DO NOTHING;
END
$$;

COMMIT;
