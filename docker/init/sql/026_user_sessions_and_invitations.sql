-- Lightweight selectable-user authentication and private session sharing.

BEGIN;

CREATE TABLE IF NOT EXISTS game_instance.app_user (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    display_name text NOT NULL,
    role_code text NOT NULL DEFAULT 'user',
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT app_user_role_ck CHECK (role_code IN ('user', 'admin'))
);

INSERT INTO game_instance.app_user (user_id, username, display_name, role_code)
VALUES
