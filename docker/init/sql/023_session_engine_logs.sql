-- Persist detailed engine activity for the live admin diagnostics view.

BEGIN;

CREATE TABLE IF NOT EXISTS game_instance.session_engine_log (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES game_instance.game_session (session_id) ON DELETE CASCADE,
    log_level text NOT NULL DEFAULT 'INFO',
    log_source text NOT NULL,
    message text NOT NULL,
    context_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_engine_log_level_ck
        CHECK (log_level IN ('TRACE', 'DEBUG', 'INFO', 'WARN', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS session_engine_log_session_idx
    ON game_instance.session_engine_log (session_id, log_id);

CREATE OR REPLACE FUNCTION game_instance.fn_session_engine_logs(
    p_session_id bigint,
    p_after_log_id bigint DEFAULT 0
) RETURNS TABLE (
    log_id bigint,
    session_id bigint,
    log_level text,
    log_source text,
    message text,
    context_json jsonb,
    created_at timestamptz
) LANGUAGE sql STABLE AS $$
    SELECT l.log_id, l.session_id, l.log_level, l.log_source,
           l.message, l.context_json, l.created_at
    FROM game_instance.session_engine_log l
    WHERE l.session_id = p_session_id
      AND l.log_id > p_after_log_id
    ORDER BY l.log_id
$$;

CREATE OR REPLACE PROCEDURE game_instance.sp_engine_log_append(
    IN p_session_id bigint,
    IN p_log_level text,
    IN p_log_source text,
    IN p_message text,
    IN p_context_json jsonb,
    INOUT p_log_id bigint
) LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO game_instance.session_engine_log
        (session_id, log_level, log_source, message, context_json)
    VALUES
        (p_session_id, COALESCE(p_log_level, 'INFO'), COALESCE(p_log_source, 'ENGINE'),
         p_message, COALESCE(p_context_json, '{}'::jsonb))
    RETURNING log_id INTO p_log_id;
END;
$$;

COMMIT;
