-- Replace the old static match-definition tables with game modes.
-- A game mode is a configured way to play a game; it is not a user's
-- runtime game instance, which belongs in game_instance.

BEGIN;

CREATE TABLE IF NOT EXISTS game_engine.game_mode (
    game_mode_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint NOT NULL REFERENCES game_engine.game (game_id),
    parent_game_mode_id bigint REFERENCES game_engine.game_mode (game_mode_id),
    game_mode_code text NOT NULL,
    game_mode_name text NOT NULL,
    game_mode_description text,
    mode_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_game_code_uq
        UNIQUE (game_id, game_mode_code)
);

CREATE TABLE IF NOT EXISTS game_engine.game_mode_rule (
    game_mode_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_mode_id bigint NOT NULL REFERENCES game_engine.game_mode (game_mode_id),
    game_rule_id bigint NOT NULL REFERENCES game_engine.game_rule (game_rule_id),
    rule_order integer NOT NULL DEFAULT 0,
    rule_config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT game_mode_rule_order_ck
        CHECK (rule_order >= 0),
    CONSTRAINT game_mode_rule_owner_uq
        UNIQUE (game_mode_id, game_rule_id),
    CONSTRAINT game_mode_rule_order_uq
        UNIQUE (game_mode_id, rule_order)
);

DO $migration$
BEGIN
    IF to_regclass('game_engine.match') IS NOT NULL THEN
        EXECUTE $sql$
            INSERT INTO game_engine.game_mode
                (game_id, game_mode_code, game_mode_name,
                 game_mode_description, mode_config_json)
            SELECT m.game_id,
                   lower(regexp_replace(m.match_name, '[^a-zA-Z0-9]+', '_', 'g')),
                   m.match_name,
                   m.match_description,
                   jsonb_build_object(
                       'mode_type', lower(regexp_replace(m.match_name, '[^a-zA-Z0-9]+', '_', 'g')),
                       'players', jsonb_build_object(
                           'minimum', g.minimum_number_of_players,
                           'maximum', g.maximum_number_of_players
                       ),
                       'status', 'reference_only'
                   )
            FROM game_engine."match" m
            JOIN game_engine.game g ON g.game_id = m.game_id
            ON CONFLICT (game_id, game_mode_code) DO NOTHING
        $sql$;

        EXECUTE $sql$
            INSERT INTO game_engine.game_mode_rule
                (game_mode_id, game_rule_id, rule_order, rule_config_json)
            SELECT gm.game_mode_id,
                   gr.game_rule_id,
                   row_number() OVER (
                       PARTITION BY gm.game_mode_id
                       ORDER BY gr.game_rule_id
                   ) - 1,
                   '{}'::jsonb
            FROM game_engine.game_mode gm
            JOIN game_engine.game_rule gr ON gr.game_id = gm.game_id
            ON CONFLICT (game_mode_id, game_rule_id) DO NOTHING
        $sql$;

        EXECUTE 'DROP TABLE game_engine."match"';
    END IF;

    IF to_regclass('game_engine.match_attribute') IS NOT NULL THEN
        EXECUTE 'DROP TABLE game_engine.match_attribute';
    END IF;
END
$migration$;

COMMENT ON TABLE game_engine.game_mode IS
    'A configured way to play a game, including mode-specific JSON structure.';
COMMENT ON TABLE game_engine.game_mode_rule IS
    'Rules enabled by a game mode, with ordering and mode-specific configuration.';

COMMIT;
